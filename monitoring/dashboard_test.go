// panels returns every panel of d in layout order.
func panels(d Dashboard) []Panel {
	var out []Panel
	for _, r := range d.Rows {
		for _, g := range r.Groups {
			out = append(out, g.Panels...)
		}
	}
	return out
}

// doc decodes the dashboard's JSON, the resource Grafana reads.
func doc(t *testing.T, d Dashboard) obj {
	t.Helper()
	b, err := DashboardJSON(Default(), d)
	if err != nil {
		t.Fatalf("%s: %v", d.Name, err)
	}
	var out obj
	if err := json.Unmarshal(b, &out); err != nil {
		t.Fatalf("%s: %v", d.Name, err)
	}
	return out
}

// elementsOf returns the panel spec of every element by element name.
func elementsOf(t *testing.T, d Dashboard) map[string]obj {
	t.Helper()
	spec := field[obj](t, doc(t, d), "spec", d.Name)
	out := map[string]obj{}
	for name, e := range field[obj](t, spec, "elements", d.Name) {
		el, ok := e.(obj)
		if !ok {
			t.Fatalf("%s: element %s is %T, want object", d.Name, name, e)
		}
		if el["kind"] != "Panel" {
			t.Errorf("%s: element %s kind = %v, want Panel", d.Name, name, el["kind"])
		}
		out[name] = field[obj](t, el, "spec", d.Name+": "+name)
	}
	return out
}

// placement is where the layout puts one element: the minimum column width
// of its auto grid and how many times it appears.
type placement struct {
	width, count int
}

// placements walks the dashboard's layout and returns the placement of
// every element it references.
func placements(t *testing.T, d Dashboard) map[string]*placement {
	t.Helper()
	spec := field[obj](t, doc(t, d), "spec", d.Name)
	out := map[string]*placement{}
	var walk func(layout obj, where string)
	walk = func(layout obj, where string) {
		ls := field[obj](t, layout, "spec", where)
		switch kind := layout["kind"]; kind {
		case "RowsLayout":
			for _, r := range field[[]any](t, ls, "rows", where) {
				row, _ := r.(obj)
				if row["kind"] != "RowsLayoutRow" {
					t.Errorf("%s: row kind %v", where, row["kind"])
				}
				rs := field[obj](t, row, "spec", where)
				walk(field[obj](t, rs, "layout", where), where+" / "+fmt.Sprint(rs["title"]))
			}
		case "AutoGridLayout":
			if ls["columnWidthMode"] != "custom" {
				t.Errorf("%s: columnWidthMode = %v, want custom", where, ls["columnWidthMode"])
			}
			switch ls["rowHeightMode"] {
			case "short", "standard", "tall":
			default:
				t.Errorf("%s: rowHeightMode = %v", where, ls["rowHeightMode"])
			}
			if num(t, ls, "maxColumnCount", where) < 1 {
				t.Errorf("%s: maxColumnCount below 1", where)
			}
			width := num(t, ls, "columnWidth", where)
			for _, i := range field[[]any](t, ls, "items", where) {
				item, _ := i.(obj)
				if item["kind"] != "AutoGridLayoutItem" {
					t.Errorf("%s: item kind %v", where, item["kind"])
				}
				ref := field[obj](t, field[obj](t, item, "spec", where), "element", where)
				if ref["kind"] != "ElementReference" {
					t.Errorf("%s: element reference kind %v", where, ref["kind"])
				}
				name := field[string](t, ref, "name", where)
				if out[name] == nil {
					out[name] = &placement{}
				}
				out[name].width = width
				out[name].count++
			}
		default:
			t.Errorf("%s: layout kind %v, want RowsLayout or AutoGridLayout", where, kind)
		}
	}
	walk(field[obj](t, spec, "layout", d.Name), d.Name)
	return out
}

func TestLayoutPlacesEveryElementOnce(t *testing.T) {
	for _, d := range Dashboards() {
		elements := elementsOf(t, d)
		placed := placements(t, d)
		for name, p := range placed {
			if p.count != 1 {
				t.Errorf("%s: layout references %s %d times", d.Name, name, p.count)
			}
			if _, ok := elements[name]; !ok {
				t.Errorf("%s: layout references missing element %s", d.Name, name)
			}
		}
		for name, e := range elements {
			if placed[name] == nil {
				t.Errorf("%s: element %s is not in the layout", d.Name, name)
			}
			if want := fmt.Sprintf("panel-%d", num(t, e, "id", name)); name != want {
				t.Errorf("%s: element %s holds panel id %s", d.Name, name, want)
			}
		}
		if len(elements) != len(panels(d)) {
			t.Errorf("%s: %d elements for %d panels", d.Name, len(elements), len(panels(d)))
		}
	}
}

