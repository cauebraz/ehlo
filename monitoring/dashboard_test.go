const root = ".."

func TestCommittedFilesAreTheDefaultRender(t *testing.T) {
	files, err := filepath.Glob(filepath.Join(root, "grafana/dashboards/*.json"))
	if err != nil {
		t.Fatal(err)
	}
	render, err := Files(Default(), FormatAll)
	if err != nil {
		t.Fatal(err)
	}
	generated := map[string]bool{}
	for _, d := range Dashboards() {
		file := uid(d) + ".json"
		generated[file] = true
		got, err := os.ReadFile(filepath.Join(root, "grafana/dashboards", file))
		if err != nil || !bytes.Equal(got, render[DashboardsDir+"/"+file]) {
			t.Errorf("grafana/dashboards/%s differs from the code, run ehlo-monitoring update", file)
		}
	}
	for _, f := range files {
		if !generated[filepath.Base(f)] {
			t.Errorf("%s is not generated by the code", f)
		}
	}
	for _, file := range []string{RecordingFile, AlertsFile} {
		got, err := os.ReadFile(filepath.Join(root, "prometheus/rules", file))
		if err != nil || !bytes.Equal(got, render[RulesDir+"/"+file]) {
			t.Errorf("prometheus/rules/%s differs from the code, run ehlo-monitoring update", file)
		}
	}
}

