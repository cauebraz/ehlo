func TestAlertQueriesSelectEhloAlerts(t *testing.T) {
	for _, metric := range []string{"ALERTS", "GRAFANA_ALERTS"} {
		cfg := Default()
		cfg.AlertsMetric = metric
		alerts := regexp.MustCompile(`\b(GRAFANA_)?ALERTS\b(\{[^}]*\})?`)
		found := 0
		for _, d := range Dashboards() {
			for where, expr := range renderedExprs(t, cfg, d) {
				for _, m := range alerts.FindAllStringSubmatch(expr, -1) {
					found++
					if !strings.HasPrefix(m[0], metric+"{") {
						t.Errorf("%s: %s, want the %s series", where, m[0], metric)
					}
					if !strings.Contains(m[2], ehloAlerts) {
						t.Errorf("%s: %s does not select %s, so other alerts in a shared Prometheus count", where, m[0], ehloAlerts)
					}
				}
			}
		}
		if found == 0 {
			t.Errorf("%s: no dashboard query reads the alert state", metric)
		}
	}
}

